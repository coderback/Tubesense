"""Measured statistics the investigator may cite, keyed so the verifier can check every number.

Read-only from the pipeline outputs (frozen v1 outputs regenerated by scripts/run_gonogo.py, plus the
post-hoc outputs), so re-running after the 24 Oct rides picks the new runs up automatically:
  level.<DIR>.<FROM>-<TO>          section mean level, dBFS(A) (uncalibrated, relative only), n runs, sd
  contrast.LST-BTH_minus_BTH-MLE   within-trip difference, dB: mean, range, n trips, sign test
  loudness.verdict                 the pre-registered loudness verdict (GO / WEAK / NO-GO)
  positioning.*                    online tracker vs the independent curve-edge truth (v1, 23 Oct)
  v2.*                             the Argon-submitted post-hoc config on the dev split (if present)
Each stat: {key, value, unit, n, detail, source}. Writes outputs_posthoc/section_stats.json and
upserts Atlas `section_stats` (when reachable).
Run: PYTHONPATH=. .venv/Scripts/python -m agent.section_stats
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs_posthoc" / "section_stats.json"


def _r(x, nd=2):
    return None if x is None else round(float(x), nd)


def build() -> dict[str, dict]:
    stats: dict[str, dict] = {}

    def put(key, value, unit, n=None, detail=None, source=""):
        stats[key] = {"key": key, "value": value, "unit": unit, "n": n, "detail": detail or {}, "source": source}

    lf = ROOT / "outputs" / "gonogo" / "loudness.json"
    L = json.load(open(lf))
    src = "outputs/gonogo/loudness.json"
    for a in L["aggregate_by_section_direction"]["LAeq"]:
        f, t = a["section"].split("->")
        put(f"level.{a['direction']}.{f}-{t}", _r(a["mean"]), "dBFS(A), uncalibrated", a["n"],
            {"sd": _r(a["sd"]), "runs": a["runs"], "excluded": a["excluded"]}, src)
    durs: dict[str, list[float]] = {}
    for s in L["sections"]:
        if not s.get("placement_excluded") and s.get("depart_observed") and s.get("arrive_observed"):
            durs.setdefault(f"duration.{s['direction']}.{s['from']}-{s['to']}", []).append(float(s["wall_dur_s"]))
    for k, v in durs.items():
        put(k, _r(sum(v) / len(v), 1), "s, departure to arrival (mean)", len(v),
            {"min": _r(min(v), 1), "max": _r(max(v), 1)}, src)
    c = L["paired_differences"]["summary"]["placement_ok"]
    la = c["LAeq"]
    put("contrast.LST-BTH_minus_BTH-MLE", _r(la["mean_db"]), "dB (within trip)", c["n"],
        {"sd": _r(la["sd_db"]), "min": _r(la["min_db"]), "max": _r(la["max_db"]), "n_positive": la["n_positive"],
         "sign_test_p_one_sided": _r(la["sign_test_p_one_sided"], 4), "trips": c["trips"]}, src)
    put("loudness.verdict", L["verdict"]["verdict"], "pre-registered verdict", None,
        {"justification": L["verdict"]["justification"]}, src)

    O = json.load(open(ROOT / "outputs" / "online" / "online_eval.json"))["overall"]
    src = "outputs/online/online_eval.json"
    put("positioning.median_error_m", O["map_vs_independent_m_median_of_runs"], "m (vs yaw curve-edge proxy)",
        O["n_runs"], {"metres": "straight-line chord scaled (v1)"}, src)
    put("positioning.timetable_median_m", O["timetable_vs_independent_m_median_of_runs"], "m", O["n_runs"], {}, src)
    put("positioning.between_curves_median_m", O["edges_masked_map_m_median_of_runs"], "m", O["n_runs"],
        {"meaning": "yaw hidden around each curve edge"}, src)
    put("positioning.band90_coverage_mean", O["band90_coverage_independent_mean"], "fraction", O["n_runs"], {}, src)

    fc = ROOT / "outputs_posthoc" / "final_config.json"
    lg = ROOT / "outputs_posthoc" / "attempts.jsonl"
    if fc.exists() and lg.exists():
        final = json.load(open(fc))
        rows = [json.loads(x) for x in open(lg, encoding="utf-8") if x.strip()]
        dev = next((r for r in rows if r["kind"] == "dev" and r["config_hash"] == final["config_hash"]), None)
        test = next((r for r in rows if r["kind"] == "test"), None)
        src = "outputs_posthoc/attempts.jsonl"
        if dev:
            m = dev["metrics"]
            put("v2.dev.median_error_m", m["median_error_m"], "m (vs yaw curve-edge proxy, WTT metres)", m["n_runs"],
                {"config": final["config"], "vs_baseline": dev.get("vs_baseline")}, src)
            put("v2.dev.band90_coverage_mean", m["coverage_mean"], "fraction", m["n_runs"], {}, src)
        put("v2.dev.n_configs_tried", sum(r["kind"] == "dev" for r in rows), "configurations", None, {}, src)
        if test:
            m = test["metrics"]
            put("v2.test.median_error_m", m["median_error_m"], "m (24 Oct, forward test)", m["n_runs"], {}, src)
            put("v2.test.timetable_median_m", m["timetable_median_m"], "m", m["n_runs"], {}, src)
            put("v2.test.band90_coverage_mean", m["coverage_mean"], "fraction", m["n_runs"], {}, src)
    return stats


def main():
    stats = build()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(stats, indent=1, default=float), encoding="utf-8")
    try:
        sys.path.insert(0, str(ROOT))
        from atlas.db import db
        from pymongo import ReplaceOne
        d = db()
        d.section_stats.bulk_write([ReplaceOne({"_id": k}, {"_id": k, **v}, upsert=True) for k, v in stats.items()])
        d.section_stats.delete_many({"_id": {"$nin": list(stats)}})
        print(f"atlas section_stats: {d.section_stats.count_documents({})}")
    except Exception as e:  # noqa: BLE001
        print(f"(atlas skipped: {type(e).__name__})")
    for k, v in stats.items():
        print(f"{k:42s} {v['value']} {v['unit']} (n={v['n']})")


if __name__ == "__main__":
    main()
